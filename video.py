"""Trillion video maker: renders a short cinematic social video to MP4, fully on this PC.

It builds the video from scenes (a headline, a caption and optionally one of your own photos per
scene) with slow camera moves, film grain, letterbox bars and animated titles, then encodes it with
FFmpeg. No footage is generated by AI here; that needs a separate video model.
"""
import glob, math, os, random, shutil, subprocess
from pathlib import Path

from PIL import Image, ImageChops, ImageDraw, ImageFilter, ImageFont

SIZES = {"vertical": (1080, 1920), "square": (1080, 1080), "landscape": (1920, 1080)}
FPS = 30
IMAGE_EXT = (".jpg", ".jpeg", ".png", ".webp", ".bmp")


def find_ffmpeg():
    p = shutil.which("ffmpeg")
    if p:
        return p
    local = os.environ.get("LOCALAPPDATA", "")
    for pat in (r"Microsoft\WinGet\Links\ffmpeg.exe", r"Microsoft\WinGet\Packages\Gyan.FFmpeg*\**\bin\ffmpeg.exe"):
        hits = glob.glob(os.path.join(local, pat), recursive=True)
        if hits:
            return hits[0]
    raise RuntimeError("FFmpeg was not found. Run '1 - Setup.bat' again, then restart Trillion.")


def _font(size, bold=True):
    win = os.path.join(os.environ.get("WINDIR", r"C:\Windows"), "Fonts")
    names = (["bahnschrift.ttf", "segoeuib.ttf", "arialbd.ttf"] if bold else ["segoeui.ttf", "arial.ttf"])
    cands = [os.path.join(win, n) for n in names] + [
        "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf" if bold else "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"]
    for c in cands:
        if os.path.exists(c):
            f = ImageFont.truetype(c, size)
            if "bahnschrift" in c.lower():
                try:
                    f.set_variation_by_name("Bold")
                except Exception:
                    pass
            return f
    return ImageFont.load_default()


def _hex(c, default=(255, 180, 84)):
    try:
        c = c.lstrip("#")
        return tuple(int(c[i:i + 2], 16) for i in (0, 2, 4))
    except Exception:
        return default


def _wrap(draw, text, font, max_w):
    lines, cur = [], ""
    for word in str(text).split():
        trial = (cur + " " + word).strip()
        if draw.textlength(trial, font=font) <= max_w or not cur:
            cur = trial
        else:
            lines.append(cur)
            cur = word
    if cur:
        lines.append(cur)
    return lines[:5]


def _ease(t):
    t = max(0.0, min(1.0, t))
    return 1 - (1 - t) ** 3


def _abstract_bg(w, h, accent, seed):
    """A moody light-leak backdrop for scenes without a photo."""
    rnd = random.Random(seed)
    W, H = int(w * 1.3), int(h * 1.3)
    small = Image.new("RGB", (W // 8, H // 8), (9, 8, 13))
    d = ImageDraw.Draw(small)
    teal = (40, 190, 200)
    for i in range(7):
        col = accent if i % 2 == 0 else teal
        col = tuple(int(c * rnd.uniform(0.35, 0.8)) for c in col)
        r = rnd.randint(small.width // 6, small.width // 2)
        x, y = rnd.randint(0, small.width), rnd.randint(0, small.height)
        d.ellipse([x - r, y - r, x + r, y + r], fill=col)
    small = small.filter(ImageFilter.GaussianBlur(small.width // 7))
    return small.resize((W, H), Image.BICUBIC)


def _cover(img, w, h, scale=1.3):
    """Resize a photo so it covers the frame with room to move the camera."""
    img = img.convert("RGB")
    k = max(w * scale / img.width, h * scale / img.height)
    return img.resize((max(w, int(img.width * k)), max(h, int(img.height * k))), Image.LANCZOS)


def _camera(base, w, h, t, move):
    """Slow push-in or pull-out with a drift (the Ken Burns move)."""
    z0, z1, dx, dy = move
    z = z0 + (z1 - z0) * t
    cw, ch = int(w * z), int(h * z)
    cw, ch = min(cw, base.width), min(ch, base.height)
    cx = (base.width - cw) / 2 + dx * (base.width - cw) / 2 * (t * 2 - 1)
    cy = (base.height - ch) / 2 + dy * (base.height - ch) / 2 * (t * 2 - 1)
    box = (int(cx), int(cy), int(cx) + cw, int(cy) + ch)
    return base.resize((w, h), Image.BILINEAR, box=box)


def _overlays(w, h):
    grad = Image.new("L", (1, h))
    for y in range(h):
        t = y / h
        grad.putpixel((0, y), int(255 * (0.20 + 0.62 * max(0.0, (t - 0.35) / 0.65) ** 1.4)))
    shade = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    shade.putalpha(grad.resize((w, h)))
    vig = Image.new("L", (w // 8, h // 8), 0)
    ImageDraw.Draw(vig).ellipse([-w // 40, -h // 40, w // 8 + w // 40, h // 8 + h // 40], fill=255)
    vig = vig.filter(ImageFilter.GaussianBlur(w // 28)).resize((w, h), Image.BICUBIC)
    vig = Image.eval(vig, lambda v: 110 + int(v * 145 / 255))
    vig = Image.merge("RGB", (vig, vig, vig))
    grains = []
    for i in range(5):
        n = Image.effect_noise((w // 2, h // 2), 26).resize((w, h), Image.NEAREST)
        g = Image.new("RGBA", (w, h), (255, 255, 255, 0))
        g.putalpha(Image.eval(n, lambda v: max(0, min(255, int(abs(v - 128) * 0.55)))))
        grains.append(g)
    return shade, vig, grains


def render(out_path, brand, scenes, website="", accent="#ffb454", fmt="vertical", seconds=20,
           music=None, images=None, progress=None):
    w, h = SIZES.get(fmt, SIZES["vertical"])
    accent = _hex(accent)
    seconds = max(6, min(60, int(seconds or 20)))
    scenes = [s for s in (scenes or []) if isinstance(s, dict) and (s.get("headline") or s.get("caption"))][:8]
    if not scenes:
        raise ValueError("The video needs at least one scene with a headline.")
    images = list(images or [])
    end_len = 3.0
    per = (seconds - end_len) / len(scenes)
    total = int(seconds * FPS)
    margin = int(w * 0.08)
    f_head = _font(int(w * (0.105 if fmt != "landscape" else 0.062)))
    f_cap = _font(int(w * (0.040 if fmt != "landscape" else 0.024)), bold=False)
    f_tag = _font(int(w * (0.030 if fmt != "landscape" else 0.018)))
    f_brand = _font(int(w * (0.15 if fmt != "landscape" else 0.09)))
    shade, vig, grains = _overlays(w, h)
    bar = int(h * (0.045 if fmt == "vertical" else 0.10))
    rnd = random.Random(7)

    prepared = []
    for i, s in enumerate(scenes):
        img = None
        src = s.get("image") or (images[i % len(images)] if images else None)
        if src and os.path.exists(str(src)):
            try:
                img = _cover(Image.open(src), w, h)
            except Exception:
                img = None
        base = img or _abstract_bg(w, h, accent, seed=i + 1)
        # crop size relative to the frame: 1.22 -> 1.0 pushes in, 1.0 -> 1.22 pulls out
        move = (1.22, 1.0, rnd.uniform(-1, 1), rnd.uniform(-0.6, 0.6)) if i % 2 == 0 else \
               (1.0, 1.22, rnd.uniform(-1, 1), rnd.uniform(-0.6, 0.6))
        probe = ImageDraw.Draw(Image.new("RGB", (8, 8)))
        head = _wrap(probe, str(s.get("headline", "")).upper(), f_head, w - 2 * margin)
        cap = _wrap(probe, s.get("caption", ""), f_cap, w - 2 * margin)
        prepared.append({"base": base, "move": move, "head": head, "cap": cap})
    end_bg = _abstract_bg(w, h, accent, seed=99)

    ff = find_ffmpeg()
    Path(out_path).parent.mkdir(parents=True, exist_ok=True)
    cmd = [ff, "-y", "-v", "error", "-f", "rawvideo", "-pix_fmt", "rgb24", "-s", f"{w}x{h}", "-r", str(FPS), "-i", "-"]
    if music and os.path.exists(str(music)):
        cmd += ["-i", str(music), "-c:a", "aac", "-b:a", "192k", "-shortest",
                "-af", f"afade=t=in:d=1,afade=t=out:st={seconds - 2}:d=2"]
    cmd += ["-c:v", "libx264", "-preset", "medium", "-crf", "18", "-pix_fmt", "yuv420p",
            "-movflags", "+faststart", "-t", str(seconds), str(out_path)]
    proc = subprocess.Popen(cmd, stdin=subprocess.PIPE, stderr=subprocess.PIPE)

    def text_layer(sc, lt, idx):
        layer = Image.new("RGBA", (w, h), (0, 0, 0, 0))
        d = ImageDraw.Draw(layer)
        lh = int(f_head.size * 1.06)
        ch = int(f_cap.size * 1.35)
        block = len(sc["head"]) * lh + (int(h * 0.03) + len(sc["cap"]) * ch if sc["cap"] else 0)
        y = int(h * (0.80 if fmt == "vertical" else 0.84)) - block
        a = _ease(lt / 0.5)
        d.rectangle([margin, y - int(h * 0.035), margin + int(w * 0.16 * _ease(lt / 0.7)), y - int(h * 0.035) + max(4, w // 180)],
                    fill=accent + (255,))
        for j, line in enumerate(sc["head"]):
            la = _ease((lt - 0.12 * j) / 0.55)
            d.text((margin, y + j * lh + int((1 - la) * h * 0.03)), line, font=f_head, fill=(255, 255, 255, int(255 * la)))
        cy = y + len(sc["head"]) * lh + int(h * 0.03)
        ca = _ease((lt - 0.55) / 0.6)
        for j, line in enumerate(sc["cap"]):
            d.text((margin, cy + j * ch), line, font=f_cap, fill=(235, 228, 216, int(255 * ca)))
        d.text((margin, bar + int(h * 0.03)), "  ".join(brand.upper()), font=f_tag, fill=accent + (int(255 * a),))
        num = f"{idx + 1:02d} / {len(prepared):02d}"
        d.text((w - margin - d.textlength(num, font=f_tag), bar + int(h * 0.03)), num, font=f_tag,
               fill=(255, 255, 255, int(170 * a)))
        return layer

    cache = {}
    try:
        for n in range(total):
            t = n / FPS
            if t < seconds - end_len:
                idx = min(len(prepared) - 1, int(t / per))
                sc = prepared[idx]
                lt = t - idx * per
                frame = _camera(sc["base"], w, h, lt / per, sc["move"])
                frame.paste(shade, (0, 0), shade)
                if lt > 1.4:  # titles have settled: reuse the finished layer
                    layer = cache.get(idx) or cache.setdefault(idx, text_layer(sc, 9.0, idx))
                else:
                    layer = text_layer(sc, lt, idx)
                frame.paste(layer, (0, 0), layer)
                fade = min(1.0, lt / 0.35, (per - lt) / 0.35) if len(prepared) > 1 or idx == 0 else 1.0
            else:
                lt = t - (seconds - end_len)
                frame = _camera(end_bg, w, h, lt / end_len, (1.25, 1.05, 0.3, 0.2))
                layer = Image.new("RGBA", (w, h), (0, 0, 0, 0))
                d = ImageDraw.Draw(layer)
                fb = f_brand
                while d.textlength(brand.upper(), font=fb) > w - 2 * margin and fb.size > 30:
                    fb = _font(int(fb.size * 0.9))
                a = _ease(lt / 0.6)
                bw = d.textlength(brand.upper(), font=fb)
                by = int(h * 0.44) - fb.size // 2
                d.text(((w - bw) / 2, by + int((1 - a) * h * 0.02)), brand.upper(), font=fb, fill=(255, 255, 255, int(255 * a)))
                lw = int(w * 0.22 * _ease((lt - 0.3) / 0.6))
                ly = by + int(fb.size * 1.25)
                d.rectangle([(w - lw) / 2, ly, (w + lw) / 2, ly + max(4, w // 180)], fill=accent + (255,))
                if website:
                    site = website.replace("https://", "").replace("http://", "").strip("/")
                    sa = _ease((lt - 0.6) / 0.6)
                    d.text(((w - d.textlength(site, font=f_cap)) / 2, ly + int(h * 0.03)), site, font=f_cap,
                           fill=(235, 228, 216, int(255 * sa)))
                frame.paste(layer, (0, 0), layer)
                fade = min(1.0, lt / 0.35, (end_len - lt) / 0.6)
            frame = ImageChops.multiply(frame, vig)
            g = grains[n % len(grains)]
            frame.paste(g, (0, 0), g)
            if fade < 1.0:
                frame = Image.eval(frame, lambda v, f=max(0.0, fade): int(v * f))
            bh = int(bar * _ease(t / 0.8))
            if bh:
                ImageDraw.Draw(frame).rectangle([0, 0, w, bh], fill=(0, 0, 0))
                ImageDraw.Draw(frame).rectangle([0, h - bh, w, h], fill=(0, 0, 0))
            proc.stdin.write(frame.tobytes())
            if progress and n % 30 == 0:
                progress(int(100 * n / total))
        proc.stdin.close()
        err = proc.stderr.read().decode(errors="replace")
        if proc.wait() != 0:
            raise RuntimeError("FFmpeg could not write the video: " + err[-300:])
    except BrokenPipeError:
        raise RuntimeError("FFmpeg stopped early: " + proc.stderr.read().decode(errors="replace")[-300:])
    finally:
        if proc.poll() is None:
            proc.kill()
    return {"path": str(out_path), "seconds": seconds, "size": f"{w}x{h}", "scenes": len(prepared),
            "has_music": bool(music and os.path.exists(str(music)))}


def images_in(folder):
    p = Path(folder)
    if not p.is_dir():
        return []
    return sorted(str(f) for f in p.iterdir() if f.suffix.lower() in IMAGE_EXT)[:8]
